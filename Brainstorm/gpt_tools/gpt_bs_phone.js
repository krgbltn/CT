function unwrapKnowledgeBaseLinks(text) {
	const references = new Set()
	text = text.replace(/^[ \t]{0,3}\[([^\]\n]+)\]:[^\n]*(?:\n[ \t]+["'][^\n]*["'])?/gm, (_match, id) => {
		references.add(id.trim().toLowerCase())
		return ''
	})
	// Сканируем скобки, чтобы URL с вложенными скобками не оставляли хвосты.
	function closingBracket(start, open, close) {
		let depth = 0
		for (let i = start; i < text.length; i++) {
			if (text[i] === '\\') { i++; continue }
			if (text[i] === open) depth++
			if (text[i] === close && --depth === 0) return i
		}
		return -1
	}
	let result = ''
	for (let i = 0; i < text.length;) {
		const image = text[i] === '!' && text[i + 1] === '['
		const start = image ? i + 1 : i
		if (text[start] !== '[') { result += text[i++]; continue }
		const end = closingBracket(start, '[', ']')
		if (end === -1) { result += text[i++]; continue }
		const label = text.slice(start + 1, end)
		let next = end + 1
		while (text[next] === ' ' || text[next] === '\t') next++
		if (text[next] === '(') {
			const targetEnd = closingBracket(next, '(', ')')
			if (targetEnd !== -1) {
				const button = /^\s*type\s*:/i.test(text.slice(next + 1, targetEnd))
				if (!image && !button) result += unwrapKnowledgeBaseLinks(label)
				i = targetEnd + 1
				continue
			}
		} else if (text[next] === '[') {
			const refEnd = closingBracket(next, '[', ']')
			if (refEnd !== -1) {
				if (!image) result += label
				i = refEnd + 1
				continue
			}
		} else if (references.has(label.trim().toLowerCase())) {
			if (!image) result += label
			i = end + 1
			continue
		}
		result += text.slice(i, end + 1)
		i = end + 1
	}
	return result
}

function sanitizeKnowledgeBaseContent(content) {
	let text = String(content ?? '')
	// Сначала декодируем разметку, в том числе экспортированный HTML внутри HTML.
	const entities = {amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' '}
	for (let pass = 0; pass < 3; pass++) {
		text = text.replace(/&(#x[\da-f]+|#\d+|amp|lt|gt|quot|apos|nbsp);/gi, (match, entity) => {
			if (entity[0] !== '#') return entities[entity.toLowerCase()]
			const code = entity[1].toLowerCase() === 'x'
				? parseInt(entity.slice(2), 16) : parseInt(entity.slice(1), 10)
			return code > 0 && code <= 0x10ffff ? String.fromCodePoint(code) : match
		})
	}
	text = text
		.replace(/<pre\b[^>]*>\s*<code\b[^>]*\blanguage-buttons\b[^>]*>[\s\S]*?<\/code>\s*<\/pre>/gi, '')
		.replace(/<code\b[^>]*\blanguage-buttons\b[^>]*>[\s\S]*?<\/code>/gi, '')
		.replace(/(?:`{3,}|~{3,})\s*(?:language-)?buttons\b[^\n]*\n?[\s\S]*?(?:`{3,}|~{3,}|$)/gi, '')
		.replace(/<(button|script|style)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, '')
		.replace(/<([a-z][\w-]*)\b[^>]*\brole\s*=\s*["']?button["']?[^>]*>[\s\S]*?<\/\1\s*>/gi, '')
		.replace(/<!--[\s\S]*?-->/g, '')
		.replace(/<\/?(?:p|div|li|h[1-6]|br|tr)\b[^>]*>/gi, '\n')
		.replace(/<\/?[a-z][^>]*>/gi, '')
	text = unwrapKnowledgeBaseLinks(text)
	const punctuation = match => match.match(/[.,;:!?]+$/)?.[0] || ''
	return text
		.replace(/\b[a-z][a-z0-9+.-]*:\/\/[^\s<>"`]+/gi, punctuation)
		.replace(/\b(?:mailto|tel|javascript|data):[^\s<>"`]+/gi, punctuation)
		.replace(/[\p{L}\p{N}_.+%-]+@[\p{L}\p{N}.-]+\.[\p{L}]{2,}/gu, '')
		.replace(/(^|[^\p{L}\p{N}_@])(?:[\p{L}\p{N}-]+\.)+(?:[\p{L}]{2,63}|xn--[a-z0-9-]+)(?::\d+)?(?:[\/?#][^\s<>"`]*)?/giu,
			(match, prefix) => prefix + punctuation(match))
		.replace(/^[ \t]*::[ \t]*$/gm, '')
		.replace(/[ \t]+\n/g, '\n')
		.replace(/[ \t]{2,}/g, ' ')
		.replace(/\n{3,}/g, '\n\n')
		.trim()
}

