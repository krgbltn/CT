// Синтетический контекст: craftgpt парсит tool_calls и конвертирует маркер
// ".tool_name" только на /context_query с НЕПУСТЫМ контекстом (как у rupost).
// С пустым контекстом на любом эндпоинте маркер возвращается как обычный текст.
function buildSyntheticContext(question) {
	const docs = []
	docs.push({
		doc_id: 'synthetic-products',
		title: 'Каталог оборудования BRAINSTORM',
		content: `Тебе доступны следующие категории оборудования:\n\n${PRODUCT_LIST_PROMPT}\n\nПо вопросам об оборудовании, его настройке, использовании, прошивке и ошибках — находи информацию через инструмент search_in_knowledge_base, указывая product (категорию из перечня выше) и queries (список поисковых запросов). Если клиент просит найти, подобрать или выбрать датчик либо спрашивает о совместимости датчика с автомобилем (даже без парт-номера или модели авто) — не вызывай инструменты и ответь ровно фразой: ${SENSOR_SELECTION_TEXT}`,
	})
	const q = (question || '').toLowerCase()
	for (const key of Object.keys(PRODUCTS)) {
		const product = PRODUCTS[key]
		const synonyms = [product.name, key, product.queue]
			.filter(Boolean)
			.map(s => s.toLowerCase())
		if (synonyms.some(s => q.includes(s))) {
			docs.push({
				doc_id: `synthetic-${key}`,
				title: product.name,
				content: product.description,
			})
		}
	}
	return docs
}


