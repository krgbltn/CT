function sanitizeResponse(response) {
	if (!response?.answer) return response

	const answer = response.answer
		.replace(/[^\n.!?]*(?:кнопк|нажмите|перейдите|меню|ссылк)[^\n.!?]*[.!?]?/giu, '')
		.replace(/\n{3,}/g, '\n\n')
		.trim()

	return {
		...response,
		answer: answer || 'Уточните, пожалуйста, ваш вопрос.',
	}
}


