const _coreCallLLM = _callLLM
_callLLM = async function(url, data, replies, extraErrorHandling = null) {
	if (data && data.max_tokens === null) {
		delete data.max_tokens
	}
	// Прямой RAG использует ту же очистку, что и результат поисковой тулзы.
	if (Array.isArray(data?.context)) {
		data = {...data, context: data.context.map(c => ({
			doc_id: c.doc_id,
			title: sanitizeKnowledgeBaseContent(c.title),
			content: sanitizeKnowledgeBaseContent(c.content),
		}))}
	}
	logger.debug(`Body POST ${url}: ${JSON.stringify(data, null, 2)}`)
	replies.debugReply(`Body POST ${url}: ${JSON.stringify(data, null, 2)}`)
	// Здесь проходят и финальные ответы /tool_responses после поиска.
	return sanitizeResponse(await _coreCallLLM(url, data, replies, extraErrorHandling))
}


