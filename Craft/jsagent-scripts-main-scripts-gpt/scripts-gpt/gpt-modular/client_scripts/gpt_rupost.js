// Tracking/ops сценарии возвращают пользователю результат поиска как markdown-сообщение.
// Остальные сценарии — fire-and-forget или результат уходит в LLM.
RedisQueue = class extends RedisQueue {
    async onScenarioCompleted(item, scenarioResult, replies) {
        if (
            item.name === "transfer_to_tracking_scenario" ||
            item.name === "transfer_to_ops_search_scenario"
        ) {
            await replies.markdownReply(scenarioResult)
        }
    }
}

// Override: добавляет в каждый ответ слот LLM_ANSWER_HISTORY с накапливаемой
// историей текстов, отправленных пользователю в рамках текущего цикла.
// Порядок важен: mergeSlots сначала (caller-значения попадают в replySlots),
// updateAccumulatedSlot последним (читает текущий LLM_ANSWER_HISTORY и допишет).
function _sendReply(text, slots, meta = {}) {
    slotManager.mergeSlots(slots)
    updateAccumulatedSlot(AGENT_SLOTS.LLM_ANSWER_HISTORY, text)

    const reply = agentApi.makeMarkdownReply(text)
    logger.debug(JSON.stringify(reply.message.text))

    return agentApi.sendMessage({
        MessageMarkdown: reply.message.text,
        SendMessageParams: {
            ProjectId: reply.customer_id,
            OmniUserId: reply.omni_user_id,
            DestinationChannel: {
                ChannelId: reply.channel_id,
                ChannelUserId: message.user.channel_user_id,
            },
            Sender: {},
            FilledSlots: slotManager.replySlots,
            Meta: meta
        }
    }, logger)
        .then(result => {
            if (!result.Ok) {
                const errMsg = `${JSON.stringify(result.Errors)} during sending ${JSON.stringify(reply)}`
                logger.error(errMsg)
                if (DEBUG) {
                    agentApi.sendMessage({
                        MessageMarkdown: errMsg,
                        SendMessageParams: {
                            ProjectId: reply.customer_id,
                            OmniUserId: reply.omni_user_id,
                            DestinationChannel: {
                                ChannelId: reply.channel_id,
                                ChannelUserId: message.user.channel_user_id,
                            },
                            Sender: {},
                            FilledSlots: slotManager.replySlots
                        }
                    }, logger)
                }
            }
        })
        .catch(e => logger.error(`Error sending reply: ${e}.`))
}

