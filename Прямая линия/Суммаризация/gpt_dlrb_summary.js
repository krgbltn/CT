const LLM_COMPRESSION_TEMPLATE = `${LLM_SYSTEM_TEMPLATE}
ПОВТОРНОЕ СОКРАЩЕНИЕ:
Предыдущий ответ превысил ${MAX_SUMMARY_LENGTH} символов. Заново сожми исходное обращение:
по возможности объедини проблему и конкретную просьбу или вопрос в одно короткое предложение.
Убирай второстепенные обстоятельства и заменяй длинные обороты короткими, не теряя отрицаний,
ключевой причины и самостоятельных просьб. Не обрезай конец текста и не добавляй новых фактов.
Верни только готовое обращение длиной не более ${MAX_SUMMARY_LENGTH} символов с пробелами и пунктуацией.
`;

const THINK = " /think";
const NO_THINK = " /no_think";
const LLM_TIMEOUT = agentSettings.llm_timeout ?? 60;
const LLM_TEMPERATURE_SMALLTALK = agentSettings.llm_temperature_smalltalk ?? 0.7;
const LLM_TOP_P = agentSettings.llm_top_p ?? 0.95;
const LLM_TOP_K = agentSettings.llm_top_k ?? 20;
const LLM_MIN_P = agentSettings.llm_min_p ?? 0.0;
const LLM_AUTH_TOKEN = agentSettings.llm_auth_token;
const ENABLE_THINKING_SMALLTALK = agentSettings.enable_thinking_smalltalk ?? false;

function makeSummaryReplies(summary) {
	return [
		agentApi.makeTextReply(
			`/switchredirect ${aiAssistAgentId} intent_id="${articleId}"`,
			undefined,
			undefined,
			{ summary }
		)
	];
}

async function _main() {
	const value = message.slot_context?.filled_slots?.find(slot => slot.slot_id === 'question')?.value;
	const question = typeof value === 'string' ? value.trim() : '';
	if (!question) {
		logger.info('Question slot is empty. Clear summary and continue.');
		return makeSummaryReplies('');
	}

	let summary = normalizeSummary(await smalltalk(question));
	if (summary.length > MAX_SUMMARY_LENGTH) {
		logger.info({ summaryLength: summary.length }, 'Question summary is too long. Retry compression.');
		try {
			const compactSummary = normalizeSummary(await smalltalk(question, LLM_COMPRESSION_TEMPLATE));
			if (compactSummary && compactSummary.length < summary.length) {
				summary = compactSummary;
			}
		} catch (error) {
			logger.error({ stack: error.stack }, 'Question summary compression failed. Keep the first summary.');
		}
	}
	if (summary.length > MAX_SUMMARY_LENGTH) {
		logger.info({ summaryLength: summary.length }, 'Question summary still exceeds the limit. Apply fallback truncation.');
	}
	summary = limitSummaryLength(summary);
	logger.info({ summaryLength: summary.length }, 'Question summary prepared');
	return makeSummaryReplies(summary);
}

async function smalltalk(question, instruction = LLM_SYSTEM_TEMPLATE) {
	if (ENABLE_THINKING_SMALLTALK) {
		question += THINK;
	} else {
		question += NO_THINK;
	}
	const requestData = {
		question: question,
		history: null,
		temperature: LLM_TEMPERATURE_SMALLTALK,
		top_p: LLM_TOP_P,
		top_k: LLM_TOP_K,
		min_p: LLM_MIN_P,
		instruction: instruction + (ENABLE_THINKING_SMALLTALK ? '' : NO_THINK),
		last_context_price: LAST_CONTEXT_PRICE,
		other_context_price: OTHER_CONTEXT_PRICE,
		add_other_context: ADD_OTHER_CONTEXT
	};
	const response = await axios.post(
		new URL('/query', agentSettings.url_llm).href,
		requestData,
		{
			timeout: LLM_TIMEOUT * 1000,
			headers: {
				'Content-Type': 'application/json',
				'Authorization': `Bearer ${LLM_AUTH_TOKEN}`
			}
		}
	);
	return response.data.answer;
}

// Entrypoint
if (message.message_type === 1) {
	_main()
		.then(res => resolve(res))
		.catch(error => {
			logger.error({ stack: error.stack }, 'Question summary agent execution failed');
			resolve(makeSummaryReplies(''));
		});
} else {
	logger.info(`Message type: ${message.message_type}. Skip.`);
	resolve([]);
}
