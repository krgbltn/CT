const transfer_to_operator = scenario(null)(function ({ track_number, full_name, phone } = {}) {
    const clientInfo = {
        track_number: String(track_number || '').trim(),
        full_name: String(full_name || '').trim(),
        phone: String(phone || '').trim(),
    }
    if (Object.values(clientInfo).some(value => !value)) {
        return 'ERROR: track_number, full_name and phone are required before transferring to an operator'
    }
    const infoClientSlot = AGENT_SLOTS.INFO_CLIENT || 'infoclient_europochta'
    const slotValue = JSON.stringify(clientInfo)
    slotManager.setSlot(infoClientSlot, slotValue)
    logger.info(`Transfer to operator with FilledSlots: ${JSON.stringify(slotManager.replySlots)}`)
    return switchredirect(ARTICLES.TRANSFER_FOR_OPERATOR.ID)
})

